function StageCard({
  label,
  value,
  hint,
  active,
  tone = 'muted',
  disabled = false,
  onClick,
}: {
  label: string;
  value: string | number;
  hint: string;
  active: boolean;
  tone?: 'ok' | 'warn' | 'muted';
  disabled?: boolean;
  onClick: () => void;
}) {
  const { theme } = useTheme();
  const fonts = auditFonts(theme);
  const toneColor =
    tone === 'ok'
      ? theme.colors.success
      : tone === 'warn'
        ? theme.colors.warning
        : theme.colors.textSecondary;
  return (
    <button
      type="button"
      onClick={onClick}
      disabled={disabled}
      style={{
        display: 'grid',
        gap: 2,
        minWidth: 148,
        textAlign: 'left',
        padding: '7px 10px',
        borderRadius: 7,
        border: `1px solid ${
          active ? theme.colors.primary : theme.colors.border
        }`,
        background: active
          ? `${theme.colors.primary}14`
          : theme.colors.backgroundSecondary,
        color: theme.colors.text,
        cursor: disabled ? 'default' : 'pointer',
        opacity: disabled ? 0.45 : 1,
      }}
    >
      <span
        style={{
          fontSize: fonts.body,
          fontWeight: fonts.medium,
          color: theme.colors.textSecondary,
        }}
      >
        {label}
      </span>
      <span
        style={{
          fontSize: fonts.title,
          fontWeight: fonts.semibold,
          lineHeight: fonts.lineTight,
          color:
            tone === 'ok' || tone === 'warn' ? toneColor : theme.colors.text,
        }}
      >
        {value}
      </span>
      {hint ? (
        <span
          style={{
            fontSize: fonts.body,
            lineHeight: fonts.lineHeading,
            color: theme.colors.textSecondary,
          }}
        >
          {hint}
        </span>
      ) : null}
    </button>
  );
}

function IntentDetail({
  item,
  layers,
  intent,
}: {
  item: CorpusCase;
  layers: HighlightLayer[];
  intent: CorpusIntent | undefined;
}) {
  const { theme } = useTheme();
  const fonts = auditFonts(theme);
  if (!intent) return <EmptyStage>No intent selected.</EmptyStage>;

  const operation = intent.operation as AcpFileOperation;
  const workspaceItem = item.items.find(
    (entry) =>
      entry.path === intent.path && entry.operation === intent.operation,
  );
  const dropped = item.dropped.find((entry) => entry.path === intent.path);
  const layer = layerForPath(layers, intent.path);
  const inCity = cityHasPath(intent.path, intent.kind);
  const rows: Array<[string, () => React.ReactNode]> = [
    [
      'Path',
      () => <span style={{ fontFamily: fonts.mono }}>{intent.path}</span>,
    ],
    ['Operation', () => <OperationChip operation={operation} />],
    ['Kind', () => intent.kind],
    ['Source', () => intent.source ?? '—'],
    [
      'Workspace filter',
      () =>
        workspaceItem ? (
          <span style={{ color: theme.colors.success }}>retained</span>
        ) : dropped ? (
          <span style={{ color: theme.colors.warning }}>
            dropped: {dropped.reason}
          </span>
        ) : (
          <span style={{ color: theme.colors.textSecondary }}>
            not retained
          </span>
        ),
    ],
    [
      'Layer',
      () =>
        layer ? (
          <span
            style={{ display: 'inline-flex', gap: 6, alignItems: 'center' }}
          >
            <OperationChip operation={layerOperation(layer)} />
            <span
              style={{
                color: theme.colors.textSecondary,
                fontSize: fonts.body,
              }}
            >
              priority {layer.priority}
            </span>
          </span>
        ) : (
          <span style={{ color: theme.colors.textSecondary }}>—</span>
        ),
    ],
    [
      'City',
      () => (
        <span
          style={{
            color: inCity ? theme.colors.success : theme.colors.warning,
          }}
        >
          {inCity ? 'present' : 'missing'}
        </span>
      ),
    ],
  ];

  return (
    <div style={{ display: 'grid', gap: 10 }}>
      <div
        style={{
          display: 'grid',
          gridTemplateColumns: 'auto minmax(0, 1fr)',
          gap: '4px 12px',
          fontSize: fonts.body,
          alignItems: 'center',
        }}
      >
        {rows.map(([label, value]) => (
          <React.Fragment key={label}>
            <span style={{ color: theme.colors.textSecondary }}>{label}</span>
            <span style={{ minWidth: 0, wordBreak: 'break-word' }}>
              {value()}
            </span>
          </React.Fragment>
        ))}
      </div>
      <JsonBlock value={intent} maxHeight={160} />
    </div>
  );
}

function IntentsInspector({
  item,
  layers,
  selectedKey,
  onSelect,
}: {
  item: CorpusCase;
  layers: HighlightLayer[];
  selectedKey: string | null;
  onSelect: (key: string) => void;
}) {
  const { theme } = useTheme();
  const fonts = auditFonts(theme);
  const selected =
    item.intents.find((intent) => intentKey(intent) === selectedKey) ??
    item.intents[0];

  if (item.intents.length === 0) {
    return (
      <EmptyStage>
        <strong>No intents extracted.</strong> The extractor found no path in
        this call. Open <em>Recorded call</em> to inspect the input, then check
        whether the tool shape has a handler in <code>acpFileIntents.ts</code>.
      </EmptyStage>
    );
  }

  return (
    <div style={{ display: 'grid', gap: 14 }}>
      <div style={{ overflowX: 'auto' }}>
        <table
          style={{
            width: '100%',
            borderCollapse: 'collapse',
            fontSize: fonts.body,
          }}
        >
          <thead>
            <tr style={{ color: theme.colors.textSecondary }}>
              {['Operation', 'Kind', 'Path', 'Layer', 'City'].map((label) => (
                <th
                  key={label}
                  style={{
                    textAlign: 'left',
                    fontWeight: fonts.medium,
                    padding: '6px 8px',
                    borderBottom: `1px solid ${theme.colors.border}`,
                    whiteSpace: 'nowrap',
                  }}
                >
                  {label}
                </th>
              ))}
            </tr>
          </thead>
          <tbody>
            {item.intents.map((intent) => {
              const key = intentKey(intent);
              const layer = layerForPath(layers, intent.path);
              const inCity = cityHasPath(intent.path, intent.kind);
              const active = intent === selected;
              return (
                <tr
                  key={key}
                  onClick={() => onSelect(key)}
                  style={{
                    cursor: 'pointer',
                    background: active
                      ? theme.colors.backgroundSecondary
                      : 'transparent',
                  }}
                >
                  <td
                    style={{
                      padding: '6px 8px',
                      borderBottom: `1px solid ${theme.colors.border}`,
                      borderLeft: `2px solid ${
                        active ? theme.colors.primary : 'transparent'
                      }`,
                    }}
                  >
                    <OperationChip
                      operation={intent.operation as AcpFileOperation}
                    />
                  </td>
                  <td
                    style={{
                      padding: '6px 8px',
                      borderBottom: `1px solid ${theme.colors.border}`,
                      color: theme.colors.textSecondary,
                    }}
                  >
                    {intent.kind}
                  </td>
                  <td
                    style={{
                      fontFamily: fonts.mono,
                      padding: '6px 8px',
                      borderBottom: `1px solid ${theme.colors.border}`,
                      wordBreak: 'break-all',
                    }}
                  >
                    {intent.path}
                  </td>
                  <td
                    style={{
                      padding: '6px 8px',
                      borderBottom: `1px solid ${theme.colors.border}`,
                      color: theme.colors.textSecondary,
                      whiteSpace: 'nowrap',
                    }}
                  >
                    {layer ? layer.name : '—'}
                  </td>
                  <td
                    style={{
                      padding: '6px 8px',
                      borderBottom: `1px solid ${theme.colors.border}`,
                      color: inCity
                        ? theme.colors.success
                        : theme.colors.warning,
                      whiteSpace: 'nowrap',
                    }}
                  >
                    {inCity ? 'present' : 'missing'}
                  </td>
                </tr>
              );
            })}
          </tbody>
        </table>
      </div>
      <div
        style={{
          paddingTop: 12,
          borderTop: `1px solid ${theme.colors.border}`,
        }}
      >
        <IntentDetail item={item} layers={layers} intent={selected} />
      </div>
    </div>
  );
}

