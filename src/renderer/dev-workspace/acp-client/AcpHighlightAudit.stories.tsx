/**
 * Audit surface for ACP tool call → File City highlight mapping.
 *
 * The fixture is generated by `scripts/collect-acp-highlight-corpus.mjs`,
 * which replays real OpenCode tool calls through the same
 * OpenCodeACPEventProcessor the event worker uses and applies the event
 * server's workspace-relative filter. That keeps this story free of Node-only
 * imports while still showing the extractor's real output.
 *
 * Regenerate the corpus after changing the extractor:
 *   node scripts/collect-acp-highlight-corpus.mjs
 */

interface CorpusIntent {
  path: string;
  operation: string;
  kind: 'file' | 'directory';
  source?: string;
}

interface CorpusCase {
  id: string;
  category: string;
  provenance: {
    sessionId: string;
    messageId: string;
    callId: string;
    createdAt: string;
  };
  tool: {
    name: string;
    kind: string;
    status: string;
    command?: string;
    rawInput?: Record<string, unknown>;
    locations?: Array<{ path: string }>;
    content?: string;
  };
  intents: CorpusIntent[];
  items: Array<{
    path: string;
    operation: string;
    kind: 'file' | 'directory';
  }>;
  dropped: Array<{ path: string; reason: string }>;
  outcome: 'highlighted' | 'no-file-paths' | 'error';
  error?: string;
}

interface Corpus {
  generatedAt: string;
  workspace: string;
  appCommit: string;
  agentMonitoringVersion: string;
  source: {
    kind: string;
    path: string;
    sessionsScanned: number;
    toolCallsScanned: number;
    note: string;
  };
  cityFiles: string[];
  cases: CorpusCase[];
}

const corpus = corpusJson as unknown as Corpus;
const cases = corpus.cases;

const cityData: CityData = buildCityDataFromFileTree(
  buildFileSystemTreeFromFileInfoList(
    corpus.cityFiles.map((path) => {
      const name = path.split('/').pop() ?? path;
      return {
        path,
        name,
        extension: name.includes('.') ? (name.split('.').pop() ?? '') : '',
        size: 120,
        lastModified: new Date(0),
        isDirectory: false,
        relativePath: path,
      };
    }),
    'acp-highlight-corpus',
  ),
  '',
);

function caseLabel(item: CorpusCase): string {
  return item.tool.command ?? `${item.tool.name} ${item.tool.kind}`;
}

function layersForCase(item: CorpusCase): HighlightLayer[] {
  return buildAcpHighlightLayers([
    {
      status: 'completed',
      name: item.tool.name,
      kind: item.tool.kind,
      highlightItems: item.items.map((entry) => ({
        path: entry.path,
        operation: entry.operation as AcpFileOperation,
        kind: entry.kind,
      })),
    },
  ]);
}

function cityHasPath(path: string, kind: 'file' | 'directory'): boolean {
  if (kind === 'directory') {
    return cityData.districts.some((district) => district.path === path);
  }
  return cityData.buildings.some((building) => building.path === path);
}

function formatDate(iso: string): string {
  const date = new Date(iso);
  if (Number.isNaN(date.getTime())) return iso;
  return date.toISOString().slice(0, 10);
}

/**
 * Body is the minimum. If something needs to be smaller than this, it usually
 * needs to be removed or moved into an inspector instead of shrunk.
 */
function auditFonts(theme: Theme) {
  return {
    family: theme.fonts.body,
    mono: theme.fonts.monospace,
    body: theme.fontSizes[1],
    title: theme.fontSizes[2],
    page: theme.fontSizes[3],
    medium: theme.fontWeights.medium,
    semibold: theme.fontWeights.semibold,
    lineBody: theme.lineHeights.body,
    lineTight: theme.lineHeights.tight,
    lineHeading: theme.lineHeights.heading,
  };
}

function OperationChip({
  operation,
  count,
}: {
  operation: AcpFileOperation;
  count?: number;
}) {
  const { theme } = useTheme();
  const fonts = auditFonts(theme);
  const style =
    OPERATION_LAYER_STYLES[operation] ?? OPERATION_LAYER_STYLES.execute;
  return (
    <span
      style={{
        display: 'inline-flex',
        alignItems: 'center',
        gap: 6,
        padding: '2px 7px',
        borderRadius: 999,
        border: `1px solid ${style.color}`,
        color: style.color,
        background: `${style.color}14`,
        fontSize: fonts.body,
        fontVariantNumeric: 'tabular-nums',
        whiteSpace: 'nowrap',
      }}
    >
      <span
        style={{
          width: 7,
          height: 7,
          borderRadius: 999,
          background: style.color,
        }}
      />
      {style.label}
      {typeof count === 'number' ? ` · ${count}` : ''}
    </span>
  );
}

function StatusBadge({ item }: { item: CorpusCase }) {
  const { theme } = useTheme();
  const fonts = auditFonts(theme);
  const color =
    item.outcome === 'highlighted'
      ? theme.colors.success
      : item.outcome === 'error'
        ? theme.colors.error
        : theme.colors.warning;
  const label =
    item.outcome === 'highlighted'
      ? 'Highlighted'
      : item.outcome === 'no-file-paths'
        ? 'No paths'
        : 'Error';
  return (
    <span
      style={{
        fontSize: fonts.body,
        fontWeight: fonts.medium,
        color,
        border: `1px solid ${color}`,
        borderRadius: 4,
        padding: '1px 6px',
      }}
    >
      {label}
    </span>
  );
}

function CaseList({
  selectedId,
  onSelect,
}: {
  selectedId: string;
  onSelect: (id: string) => void;
}) {
  const { theme } = useTheme();
  const fonts = auditFonts(theme);
  const [query, setQuery] = useState('');
  const categories = useMemo(
    () => [...new Set(cases.map((item) => item.category))].sort(),
    [],
  );
  const [category, setCategory] = useState('all');

  const visible = cases.filter((item) => {
    if (category !== 'all' && item.category !== category) return false;
    if (!query.trim()) return true;
    return caseLabel(item).toLowerCase().includes(query.toLowerCase());
  });

  return (
    <aside
      style={{
        width: 340,
        minWidth: 300,
        borderRight: `1px solid ${theme.colors.border}`,
        display: 'flex',
        flexDirection: 'column',
        minHeight: 0,
      }}
    >
      <div
        style={{
          padding: 12,
          borderBottom: `1px solid ${theme.colors.border}`,
          display: 'grid',
          gap: 8,
        }}
      >
        <input
          value={query}
          onChange={(event) => setQuery(event.target.value)}
          placeholder="Filter commands…"
          style={{
            width: '100%',
            padding: '6px 8px',
            borderRadius: 6,
            border: `1px solid ${theme.colors.border}`,
            background: theme.colors.backgroundSecondary,
            color: theme.colors.text,
            fontSize: fonts.body,
          }}
        />
        <select
          value={category}
          onChange={(event) => setCategory(event.target.value)}
          style={{
            width: '100%',
            padding: '6px 8px',
            borderRadius: 6,
            border: `1px solid ${theme.colors.border}`,
            background: theme.colors.backgroundSecondary,
            color: theme.colors.text,
            fontSize: fonts.body,
          }}
        >
          <option value="all">All categories ({cases.length})</option>
          {categories.map((value) => (
            <option key={value} value={value}>
              {value} ({cases.filter((item) => item.category === value).length})
            </option>
          ))}
        </select>
      </div>
      <ol
        style={{
          listStyle: 'none',
          margin: 0,
          padding: 0,
          overflowY: 'auto',
          minHeight: 0,
        }}
      >
        {visible.map((item) => {
          const selected = item.id === selectedId;
          return (
            <li key={item.id}>
              <button
                type="button"
                onClick={() => onSelect(item.id)}
                style={{
                  display: 'grid',
                  gap: 5,
                  width: '100%',
                  textAlign: 'left',
                  padding: '9px 12px',
                  border: 0,
                  borderBottom: `1px solid ${theme.colors.border}`,
                  borderLeft: `3px solid ${
                    selected ? theme.colors.primary : 'transparent'
                  }`,
                  background: selected
                    ? theme.colors.backgroundSecondary
                    : 'transparent',
                  color: theme.colors.text,
                  cursor: 'pointer',
                }}
              >
                <span
                  style={{
                    fontFamily: fonts.mono,
                    fontSize: fonts.body,
                    lineHeight: fonts.lineTight,
                    overflow: 'hidden',
                    display: '-webkit-box',
                    WebkitLineClamp: 2,
                    WebkitBoxOrient: 'vertical',
                  }}
                >
                  {caseLabel(item)}
                </span>
                <span
                  style={{
                    display: 'flex',
                    alignItems: 'center',
                    gap: 6,
                    flexWrap: 'wrap',
                  }}
                >
                  <StatusBadge item={item} />
                  <span
                    style={{
                      fontSize: fonts.body,
                      color: theme.colors.textSecondary,
                    }}
                  >
                    {item.intents.length} intent
                    {item.intents.length === 1 ? '' : 's'}
                    {item.dropped.length > 0
                      ? ` · ${item.dropped.length} dropped`
                      : ''}
                  </span>
                </span>
              </button>
            </li>
          );
        })}
      </ol>
    </aside>
  );
}

