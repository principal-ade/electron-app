function CaseDetail({ item }: { item: CorpusCase }) {
  const { theme } = useTheme();
  const fonts = auditFonts(theme);
  const layers = useMemo(() => layersForCase(item), [item]);
  const highlighted = useMemo(
    () => layers.filter((layer) => (layer.items?.length ?? 0) > 0),
    [layers],
  );
  const [stage, setStage] = useState<InspectorStage>(
    item.intents.length > 0 ? 'intents' : 'call',
  );
  const [selectedIntent, setSelectedIntent] = useState<string | null>(
    item.intents[0] ? intentKey(item.intents[0]) : null,
  );
  const [selectedLayerId, setSelectedLayerId] = useState<string | null>(
    highlighted[0]?.id ?? null,
  );

  const inspectPath = (path: string | null) => {
    if (!path) return;
    const normalized = path.replace(/^\/+/, '').replace(/\/+$/, '');
    const match =
      item.intents.find((intent) => intent.path === normalized) ??
      item.intents.find(
        (intent) =>
          intent.path.endsWith(normalized) || normalized.endsWith(intent.path),
      );
    if (!match) return;
    setSelectedIntent(intentKey(match));
    setStage('intents');
  };

  const selectIntent = (intent: CorpusIntent) => {
    setSelectedIntent(intentKey(intent));
    setStage('intents');
  };

  const stageSummary: Record<
    InspectorStage,
    {
      value: string | number;
      hint: string;
      tone: 'ok' | 'warn' | 'muted';
      disabled?: boolean;
    }
  > = {
    call: {
      value: item.tool.name,
      hint:
        (item.tool.locations ?? []).filter((location) => !location.path)
          .length > 0
          ? 'empty location'
          : (item.tool.locations?.length ?? 0) > 0
            ? `${item.tool.locations?.length} location${
                item.tool.locations?.length === 1 ? '' : 's'
              }`
            : '',
      tone: 'muted',
    },
    intents: {
      value: item.intents.length,
      hint: item.intents.length > 0 ? '' : 'nothing extracted',
      tone: item.intents.length > 0 ? 'ok' : 'warn',
    },
    items: {
      value: item.items.length,
      hint:
        item.dropped.length > 0
          ? `${item.dropped.length} dropped`
          : item.items.length > 0
            ? ''
            : 'nothing retained',
      tone:
        item.items.length > 0
          ? 'ok'
          : item.intents.length > 0
            ? 'warn'
            : 'muted',
    },
    layers: {
      value: highlighted.length,
      hint: highlighted.length > 0 ? '' : 'no paint',
      tone: highlighted.length > 0 ? 'ok' : 'warn',
    },
    output: {
      value: item.tool.content ? 'recorded' : 'none',
      hint: '',
      tone: 'muted',
      disabled: !item.tool.content,
    },
  };

  return (
    <section
      style={{
        flex: 1,
        minWidth: 0,
        display: 'flex',
        flexDirection: 'column',
        minHeight: 0,
      }}
    >
      <header
        style={{
          padding: '12px 16px',
          borderBottom: `1px solid ${theme.colors.border}`,
          display: 'grid',
          gap: 6,
        }}
      >
        <div style={{ display: 'flex', alignItems: 'center', gap: 10 }}>
          <span
            style={{
              fontFamily: fonts.mono,
              fontSize: fonts.title,
              lineHeight: fonts.lineTight,
              wordBreak: 'break-word',
            }}
          >
            {caseLabel(item)}
          </span>
          <StatusBadge item={item} />
        </div>
        <div
          style={{
            display: 'flex',
            gap: 12,
            flexWrap: 'wrap',
            fontSize: fonts.body,
            color: theme.colors.textSecondary,
          }}
        >
          <span>
            {item.tool.name} · {item.tool.kind}
          </span>
          <span>{item.category}</span>
          <span>{item.provenance.sessionId}</span>
          <span>{formatDate(item.provenance.createdAt)}</span>
        </div>
      </header>

      <div
        style={{
          display: 'flex',
          gap: 8,
          padding: '10px 16px',
          borderBottom: `1px solid ${theme.colors.border}`,
          overflowX: 'auto',
        }}
      >
        {STAGES.map((entry) => (
          <StageCard
            key={entry.id}
            label={entry.label}
            value={stageSummary[entry.id].value}
            hint={stageSummary[entry.id].hint}
            tone={stageSummary[entry.id].tone}
            disabled={stageSummary[entry.id].disabled}
            active={stage === entry.id}
            onClick={() => setStage(entry.id)}
          />
        ))}
      </div>

      <div
        style={{
          flex: 1,
          minHeight: 0,
          display: 'grid',
          gridTemplateColumns: 'minmax(0, 1fr) 360px',
        }}
      >
        <div
          style={{ minHeight: 0, overflow: 'auto', padding: '12px 16px 18px' }}
        >
          {stage === 'call' ? <CallInspector item={item} /> : null}
          {stage === 'intents' ? (
            <IntentsInspector
              item={item}
              layers={highlighted}
              selectedKey={selectedIntent}
              onSelect={setSelectedIntent}
            />
          ) : null}
          {stage === 'items' ? (
            <ItemsInspector
              item={item}
              layers={highlighted}
              onSelectIntent={selectIntent}
            />
          ) : null}
          {stage === 'layers' ? (
            <LayersInspector
              item={item}
              layers={highlighted}
              selectedLayerId={selectedLayerId}
              onSelectLayer={setSelectedLayerId}
              onSelectIntent={selectIntent}
            />
          ) : null}
          {stage === 'output' ? <OutputInspector item={item} /> : null}
        </div>

        <aside
          style={{
            borderLeft: `1px solid ${theme.colors.border}`,
            display: 'flex',
            flexDirection: 'column',
            minHeight: 0,
          }}
        >
          <div
            style={{
              display: 'flex',
              alignItems: 'center',
              justifyContent: 'space-between',
              gap: 10,
              padding: '8px 12px',
              borderBottom: `1px solid ${theme.colors.border}`,
            }}
          >
            <span
              style={{
                fontSize: fonts.body,
                color: theme.colors.textSecondary,
              }}
            >
              City
            </span>
          </div>
          <div
            style={{
              height: 'min(46vh, 420px)',
              minHeight: 240,
              padding: 10,
            }}
          >
            <div
              style={{
                width: '100%',
                height: '100%',
                border: `1px solid ${theme.colors.border}`,
                borderRadius: 8,
                overflow: 'hidden',
              }}
            >
              <ArchitectureMapHighlightLayers
                cityData={cityData}
                highlightLayers={highlighted}
                fullSize
                enableZoom
                onDirectorySelect={inspectPath}
                onBuildingClick={(building) => inspectPath(building.path)}
                canvasBackgroundColor={theme.colors.background}
                defaultBuildingColor={theme.colors.backgroundSecondary}
              />
            </div>
          </div>
          <div
            style={{
              padding: '0 12px 10px',
              display: 'flex',
              gap: 6,
              flexWrap: 'wrap',
            }}
          >
            {highlighted.length > 0 ? (
              highlighted.map((layer) => (
                <OperationChip
                  key={layer.id}
                  operation={layerOperation(layer)}
                  count={layer.items?.length ?? 0}
                />
              ))
            ) : (
              <span
                style={{
                  fontSize: fonts.body,
                  color: theme.colors.textSecondary,
                }}
              >
                No layers to paint
              </span>
            )}
          </div>
          <div
            style={{
              padding: '0 12px 12px',
              display: 'grid',
              gap: 4,
              fontSize: fonts.body,
              lineHeight: fonts.lineBody,
              color: theme.colors.textSecondary,
            }}
          >
            <span>Click a district or building to inspect its intent.</span>
            {item.items.length > 0 ? (
              <span>
                {
                  item.items.filter((entry) =>
                    cityHasPath(entry.path, entry.kind),
                  ).length
                }
                /{item.items.length} item paths exist in this city
              </span>
            ) : null}
          </div>
        </aside>
      </div>
    </section>
  );
}

